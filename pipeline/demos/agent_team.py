"""Демо для ролика «команда агентов»: настоящая цепочка из 4 помощников и главного агента.

Данные — небольшой интернет-магазин керамических кружек. Каждый помощник решает одну задачу
и пишет короткую записку, главный собирает записки и задаёт владельцу один вопрос «да/нет».
Результат (реальные ответы моделей) уходит в ролик: reels/agent-team/demo.json

    python -m pipeline.demos.agent_team
"""
import json
from concurrent.futures import ThreadPoolExecutor

from ..common import REELS, llm, llm_json

SHOP = {
    "отзывы за неделю": [
        "Кружка красивая, но пришла со сколом на ручке. Упаковка тонкая.",
        "Обожаю синюю серию, взяла третью!",
        "Доставка 9 дней, долго.",
        "Ручка снова со сколом, второй раз уже.",
        "Цвет как на фото, очень довольна.",
    ],
    "наши цены": {"Синяя кружка": 1290, "Белая кружка": 990, "Набор из 2": 2290},
    "цены конкурентов": {"Синяя кружка": [1590, 1690, 1490], "Белая кружка": [890, 950], "Набор из 2": [2490]},
    "склад": {"Синяя кружка": 6, "Белая кружка": 140, "Набор из 2": 35},
    "продажи в день": {"Синяя кружка": 3, "Белая кружка": 2, "Набор из 2": 1},
    "расходы": {"упаковка за штуку": 25, "возвраты за неделю, ₽": 2580},
}

HELPERS = [
    ("Отзывы", "Ты читаешь отзывы покупателей. Найди одну главную жалобу или радость."),
    ("Цены", "Ты сравниваешь наши цены с конкурентами. Найди одну возможность или риск."),
    ("Склад", "Ты следишь за остатками. Посчитай, на сколько дней хватит товара, и найди самое срочное."),
    ("Риски", "Ты ищешь, где магазин теряет деньги. Назови одну самую дорогую проблему."),
]

RULES = ("Пиши по-русски, простыми словами, без терминов. Деньги только в рублях. "
         "Ответ — одна короткая фраза до 12 слов, с цифрой, если она есть.")


def helper(name, task):
    note = llm(f"Данные магазина:\n{json.dumps(SHOP, ensure_ascii=False)}\n\nТвоя задача: {task}",
               system=f"Ты помощник «{name}» в команде ИИ-агентов магазина. {RULES}")
    return {"agent": name, "note": note.strip().strip('"')}


def main():
    with ThreadPoolExecutor(4) as ex:
        notes = list(ex.map(lambda h: helper(*h), HELPERS))
    for n in notes:
        print(f"[{n['agent']}] {n['note']}")

    lead = llm_json(
        "Записки помощников:\n" + "\n".join(f"- {n['agent']}: {n['note']}" for n in notes) +
        "\n\nСобери их и реши, что требует решения владельца. Верни JSON: "
        '{"message": "сообщение владельцу, 2 коротких предложения: что происходит и что предлагаешь", '
        '"question": "один вопрос, на который можно ответить да или нет, до 10 слов", '
        '"effect": "что это даст в рублях или днях, до 6 слов"}',
        system=f"Ты главный агент. Беспокоишь владельца только ради решения «да/нет». {RULES.split('Ответ')[0]}")
    print("\n[Главный]", json.dumps(lead, ensure_ascii=False, indent=1))

    out = REELS / "agent-team" / "demo.json"
    out.write_text(json.dumps({"shop": SHOP, "notes": notes, "lead": lead},
                              ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nСохранено: {out}")


if __name__ == "__main__":
    main()
